# Builds logo_fx/mark_data.js for the animation engine from a mark SVG:
#   - the exact path (Path2D) and viewBox,
#   - stroke segments (centre lines) found by skeleton + probabilistic Hough on the rendered mark, merged and grouped by
#     triangle (0 = B top, 1 = B bottom, 2 = D), each with its ink width; used by the line-motion animations, which always
#     cross-fade back into the exact path,
#   - the three triangle centroids/boxes for fold/orbit animations.
#   python3 mark_data.py <mark.svg> <out.js>
import sys, re, json, subprocess, numpy as np, cv2
from skimage.morphology import skeletonize
S = "/tmp/claude-0/-home-user-3p4e/50442171-da10-52d9-9948-b5cc07f6bc8a/scratchpad"
src, out = sys.argv[1], sys.argv[2]
svg = open(src).read(); vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]
d = re.search(r' d="([^"]+)"', svg).group(1)
R = 1600; png = "/dev/shm/_mark_r.png"
subprocess.run(["node", f"{S}/logo2/svg2png.js", src, png, str(R), "#000", "#fff"], check=True)
img = cv2.imread(png, cv2.IMREAD_GRAYSCALE); ink = img < 128; sc = vb[2] / img.shape[1]
dist = cv2.distanceTransform(ink.astype(np.uint8), cv2.DIST_L2, 5)
sk = skeletonize(ink).astype(np.uint8) * 255
L = cv2.HoughLinesP(sk, 1, np.pi / 360, threshold=18, minLineLength=int(R * 0.035), maxLineGap=int(R * 0.012))
segs = [] if L is None else [list(map(float, np.array(l).ravel()[:4])) for l in L]
# merge near-collinear overlapping segments
def ang(s): return np.arctan2(s[3] - s[1], s[2] - s[0]) % np.pi
merged = []
for s in sorted(segs, key=lambda s: -np.hypot(s[2] - s[0], s[3] - s[1])):
    a = ang(s); p = np.array(s[:2]); q = np.array(s[2:]); keep = True
    for m in merged:
        b = ang(m); da = min(abs(a - b), np.pi - abs(a - b))
        if da > np.radians(4): continue
        mp, mq = np.array(m[:2]), np.array(m[2:]); dv = (mq - mp) / (np.linalg.norm(mq - mp) + 1e-9); nv = np.array([-dv[1], dv[0]])
        if abs(np.dot(p - mp, nv)) < 5 and abs(np.dot(q - mp, nv)) < 5:
            t = sorted([0, np.dot(mq - mp, dv), np.dot(p - mp, dv), np.dot(q - mp, dv)])
            m[:2] = list(mp + dv * t[0]); m[2:] = list(mp + dv * t[-1]); keep = False; break
    if keep: merged.append([float(v) for v in s])
# group by triangle: split columns at the widest empty vertical gap (B | D), then the B by the widest empty row band
cols = ink.any(axis=0); xs = np.where(cols)[0]
gaps = [(xs[i + 1] - xs[i], xs[i]) for i in range(len(xs) - 1)]
xsplit = max(gaps)[1] + max(gaps)[0] / 2 if gaps and max(gaps)[0] > 3 else img.shape[1] * 0.33
Bpart = ink[:, :int(xsplit)]; rows = np.where(Bpart.any(axis=1))[0]
rg = [(rows[i + 1] - rows[i], rows[i]) for i in range(len(rows) - 1)]
ysplit = max(rg)[1] + max(rg)[0] / 2 if rg and max(rg)[0] > 2 else img.shape[0] / 2
out_segs = []
for s in merged:
    mx, my = (s[0] + s[2]) / 2, (s[1] + s[3]) / 2
    g = 2 if mx > xsplit else (0 if my < ysplit else 1)
    n = 9; pts = [(int(s[1] + (s[3] - s[1]) * k / n), int(s[0] + (s[2] - s[0]) * k / n)) for k in range(n + 1)]
    wv = np.median([dist[min(y, img.shape[0] - 1), min(x, img.shape[1] - 1)] for y, x in pts]) * 2
    out_segs.append([round(vb[0] + s[0] * sc, 1), round(vb[1] + s[1] * sc, 1), round(vb[0] + s[2] * sc, 1), round(vb[1] + s[3] * sc, 1), g, round(max(wv, 1.5) * sc, 1)])
tris = []
for g in range(3):
    ss = [s for s in out_segs if s[4] == g]; P = np.array([[s[0], s[1]] for s in ss] + [[s[2], s[3]] for s in ss])
    tris.append({"cx": round(float(P[:, 0].mean()), 1), "cy": round(float(P[:, 1].mean()), 1), "x0": round(float(P[:, 0].min()), 1),
                 "y0": round(float(P[:, 1].min()), 1), "x1": round(float(P[:, 0].max()), 1), "y1": round(float(P[:, 1].max()), 1), "n": len(ss)})
data = {"viewBox": vb, "d": d, "segs": out_segs, "tris": tris, "split": [round(vb[0] + xsplit * sc, 1), round(vb[1] + ysplit * sc, 1)]}
open(out, "w").write("/* BIG DOGMA mark data (generated by brand/mark_data.py) */\nwindow.DOGMA_MARK = " + json.dumps(data, separators=(",", ":"), default=float) + ";\n")
print("segments", len(out_segs), "per triangle", [t["n"] for t in tris])
